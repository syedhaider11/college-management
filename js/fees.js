/* Fees ledger, payments, receipts, and printable statements. */
(function () {
  "use strict";
  const CMS = window.CMS;
  const u = CMS.utils;
  const ui = CMS.ui;

  function feeTotals(list) {
    return list.reduce(function (totals, fee) {
      const amount = Number(fee.amount) || 0;
      const paid = Math.min(Number(fee.paid) || 0, amount);
      totals.billed += amount;
      totals.collected += paid;
      totals.outstanding += Math.max(0, amount - paid);
      if (CMS.feeStatus(fee) === "Overdue") {
        totals.overdue += Math.max(0, amount - paid);
        totals.overdueCount += 1;
      }
      return totals;
    }, { billed: 0, collected: 0, outstanding: 0, overdue: 0, overdueCount: 0 });
  }

  function documentHead(college) {
    return '<div class="doc-head">' +
      '<div class="doc-brand"><span class="brand-mark">' + u.escape((college.initials || "E").slice(0, 2)) + "</span>" +
        "<div><strong>" + u.escape(college.name) + "</strong><span>" + u.escape(college.tagline || "Campus administration") + "</span></div></div>" +
      '<div class="doc-meta">' + u.escape(college.address) + "<br />" + u.escape(college.email) + " · " + u.escape(college.phone) + "</div></div>";
  }

  function statementHTML(fee, payment) {
    const student = CMS.student(fee.studentId);
    const cls = student ? CMS.classInfo(student.classId) : null;
    const program = student ? CMS.program(student.programId) : null;
    const college = CMS.data.college;
    const isReceipt = Boolean(payment);
    const latest = payment || (fee.payments && fee.payments.length ? fee.payments[fee.payments.length - 1] : null);
    const reference = isReceipt ? payment.receiptNo : (latest ? latest.receiptNo : "STATEMENT-" + fee.id.toUpperCase());
    const issued = isReceipt ? payment.date : u.todayISO();
    const balance = Math.max(0, Number(fee.amount) - Number(fee.paid));

    let paymentRows = "";
    if (isReceipt) {
      paymentRows = '<tr><td>Payment received · ' + u.escape(payment.method) + '</td><td class="num">' + u.formatDate(payment.date, "medium") + '</td><td class="amount">' + u.formatMoney(payment.amount) + "</td></tr>";
    } else if (fee.payments && fee.payments.length) {
      paymentRows = fee.payments.map(function (entry) {
        return '<tr><td>Payment · ' + u.escape(entry.method) + '<br /><span style="font-size:8.5px;color:#68736d">' + u.escape(entry.receiptNo) + "</span></td><td class=\"num\">" + u.formatDate(entry.date, "medium") + '</td><td class="amount">' + u.formatMoney(entry.amount) + "</td></tr>";
      }).join("");
    }

    return '<div class="doc-sheet">' + documentHead(college) +
      '<p class="doc-subtitle">Fee receipt · demo document</p>' +
      '<h2 class="doc-title">' + (isReceipt ? "Payment receipt" : "Fee statement") + "</h2>" +
      '<div class="doc-info">' +
        '<div class="doc-info-row"><span>Student</span><strong>' + u.escape(student ? student.name : "—") + "</strong></div>" +
        '<div class="doc-info-row"><span>Admission no.</span><strong>' + u.escape(student ? student.admissionNo : "—") + "</strong></div>" +
        '<div class="doc-info-row"><span>Programme</span><strong>' + u.escape(program ? program.name : "—") + "</strong></div>" +
        '<div class="doc-info-row"><span>Class</span><strong>' + u.escape(cls ? cls.name : "—") + "</strong></div>" +
        '<div class="doc-info-row"><span>Reference</span><strong>' + u.escape(reference) + "</strong></div>" +
        '<div class="doc-info-row"><span>Issued</span><strong>' + u.formatDate(issued, "medium") + "</strong></div>" +
        '<div class="doc-info-row"><span>Term</span><strong>' + u.escape(fee.term) + "</strong></div>" +
        '<div class="doc-info-row"><span>Due date</span><strong>' + u.formatDate(fee.dueDate, "medium") + "</strong></div>" +
      "</div>" +
      '<table class="doc-table"><thead><tr><th>Description</th><th class="num">Date</th><th class="amount">Amount</th></tr></thead><tbody>' +
        '<tr><td>' + u.escape(fee.type) + "</td><td class=\"num\">" + u.formatDate(fee.dueDate, "medium") + '</td><td class="amount">' + u.formatMoney(fee.amount) + "</td></tr>" +
        paymentRows +
      "</tbody></table>" +
      '<div class="doc-total"><span>' + (isReceipt ? "Amount received" : "Amount paid to date") + "</span><span class=\"amount\">" + u.formatMoney(isReceipt ? payment.amount : fee.paid) + "</span></div>" +
      '<div class="doc-total" style="margin-top:8px;background:#fbece9"><span>Balance remaining</span><span class="amount" style="color:#bd4f44">' + u.formatMoney(balance) + "</span></div>" +
      '<div class="doc-foot"><div>This document was generated by the Evergreen College UI prototype.<br />No real payment has been processed. Keep for demonstration only.</div>' +
        '<div class="doc-signature"><span>Authorised signature</span></div></div>' +
      '<div class="print-note"><span class="doc-stamp">Demo · not a real receipt</span></div>' +
    "</div>";
  }

  function showDocument(title, html, printTitle) {
    ui.modal.open({
      title: title,
      subtitle: "Preview the printable document before sending it to your browser's print dialog.",
      size: "modal-lg",
      body: '<div class="doc-preview">' + html + "</div>",
      footer: '<button class="btn btn-outline" type="button" data-modal-close>Close</button>' +
        '<button class="btn btn-primary" type="button" id="printDocument">' + ui.icon("printer", 15) + " Print document</button>",
      onMount: function (modal) {
        modal.querySelector("#printDocument").addEventListener("click", function () {
          ui.print(printTitle || title, html);
        });
      }
    });
  }

  function render(root, params) {
    const state = {
      q: params.get("q") || "",
      status: params.get("status") || "all",
      classId: params.get("class") || "all",
      page: 1,
      pageSize: 8,
      sortKey: "name",
      sortDir: "asc"
    };

    function filtered() {
      const q = state.q.trim().toLowerCase();
      let list = CMS.data.fees.slice();
      if (q) {
        list = list.filter(function (fee) {
          const student = CMS.student(fee.studentId);
          return (student && (student.name.toLowerCase().includes(q) || student.admissionNo.toLowerCase().includes(q))) ||
            fee.type.toLowerCase().includes(q) ||
            fee.term.toLowerCase().includes(q);
        });
      }
      if (state.status !== "all") {
        list = list.filter(function (fee) { return CMS.feeStatus(fee).toLowerCase() === state.status; });
      }
      if (state.classId !== "all") {
        list = list.filter(function (fee) {
          const student = CMS.student(fee.studentId);
          return student && student.classId === state.classId;
        });
      }
      list.sort(function (a, b) {
        let av;
        let bv;
        if (state.sortKey === "billed") { av = Number(a.amount); bv = Number(b.amount); }
        else if (state.sortKey === "balance") { av = Number(a.amount) - Number(a.paid); bv = Number(b.amount) - Number(b.paid); }
        else if (state.sortKey === "due") { av = a.dueDate; bv = b.dueDate; }
        else {
          const sa = CMS.student(a.studentId);
          const sb = CMS.student(b.studentId);
          av = sa ? sa.name.toLowerCase() : "";
          bv = sb ? sb.name.toLowerCase() : "";
        }
        const result = typeof av === "number" ? av - bv : String(av).localeCompare(String(bv));
        return state.sortDir === "asc" ? result : -result;
      });
      return list;
    }

    function statsHTML() {
      const totals = feeTotals(CMS.data.fees);
      const rate = totals.billed ? (totals.collected / totals.billed) * 100 : 0;
      return '<div class="stat-grid fee-stats">' +
        '<div class="stat-card"><div class="stat-top"><div class="stat-icon">' + ui.icon("receipt") + '</div><span class="stat-trend neutral">This term</span></div>' +
          '<div><div class="stat-label">Total billed</div><div class="stat-value">' + u.formatMoney(totals.billed, true) + "</div></div>" +
          '<div class="stat-meta">' + u.formatNumber(CMS.data.fees.length) + " student fee accounts</div></div>" +
        '<div class="stat-card"><div class="stat-top"><div class="stat-icon tone-violet">' + ui.icon("credit-card") + '</div><span class="stat-trend">' + rate.toFixed(0) + "% collected</span></div>" +
          '<div><div class="stat-label">Fees collected</div><div class="stat-value">' + u.formatMoney(totals.collected, true) + "</div></div>" +
          '<div class="stat-meta">Recorded across all demo payment methods</div></div>' +
        '<div class="stat-card"><div class="stat-top"><div class="stat-icon tone-amber">' + ui.icon("clock") + '</div><span class="stat-trend neutral">Open</span></div>' +
          '<div><div class="stat-label">Outstanding</div><div class="stat-value">' + u.formatMoney(totals.outstanding, true) + "</div></div>" +
          '<div class="stat-meta">Balances still to be collected this term</div></div>' +
        '<div class="stat-card"><div class="stat-top"><div class="stat-icon tone-coral">' + ui.icon("alert-triangle") + '</div><span class="stat-trend down">Action needed</span></div>' +
          '<div><div class="stat-label">Overdue balances</div><div class="stat-value">' + u.formatMoney(totals.overdue, true) + "</div></div>" +
          '<div class="stat-meta">' + totals.overdueCount + " " + u.plural(totals.overdueCount, "account") + " past the due date</div></div>" +
      "</div>";
    }

    function tableHTML(list) {
      const pages = Math.max(1, Math.ceil(list.length / state.pageSize));
      state.page = Math.min(state.page, pages);
      const start = (state.page - 1) * state.pageSize;
      const rows = list.slice(start, start + state.pageSize);

      if (!list.length) {
        return ui.emptyState({
          icon: "receipt",
          title: "No fee records match these filters",
          text: "Try another name, class, or payment status. Clear the filters to see the full ledger.",
          action: '<button class="btn btn-outline btn-sm" type="button" data-clear-filters>Clear filters</button>'
        });
      }

      const sortIcon = function (key) {
        if (state.sortKey !== key) return ui.icon("chevron-down", 12);
        return ui.icon(state.sortDir === "asc" ? "arrow-up" : "arrow-down", 12);
      };

      return '<div class="table-wrap"><table class="data-table fee-table">' +
        '<caption class="sr-only">Student fee accounts, balances, due dates, and payment status</caption>' +
        "<thead><tr>" +
          '<th><button class="sort-btn ' + (state.sortKey === "name" ? "is-sorted" : "") + '" type="button" data-sort="name">Student ' + sortIcon("name") + "</button></th>" +
          "<th>Class</th><th>Fee type</th>" +
          '<th class="cell-num"><button class="sort-btn ' + (state.sortKey === "billed" ? "is-sorted" : "") + '" type="button" data-sort="billed">Billed ' + sortIcon("billed") + "</button></th>" +
          "<th>Paid</th>" +
          '<th class="cell-num"><button class="sort-btn ' + (state.sortKey === "balance" ? "is-sorted" : "") + '" type="button" data-sort="balance">Balance ' + sortIcon("balance") + "</button></th>" +
          '<th><button class="sort-btn ' + (state.sortKey === "due" ? "is-sorted" : "") + '" type="button" data-sort="due">Due date ' + sortIcon("due") + "</button></th>" +
          "<th>Status</th><th class=\"cell-actions\">Actions</th>" +
        "</tr></thead><tbody>" +
        rows.map(function (fee) {
          const student = CMS.student(fee.studentId);
          const cls = student ? CMS.classInfo(student.classId) : null;
          const program = student ? CMS.program(student.programId) : null;
          const balance = Math.max(0, Number(fee.amount) - Number(fee.paid));
          const status = CMS.feeStatus(fee);
          const paidPercent = fee.amount ? Math.min(100, (Number(fee.paid) / Number(fee.amount)) * 100) : 0;
          const progressTone = status === "Paid" ? "" : status === "Overdue" ? "danger" : "warning";
          return '<tr data-fee-row="' + u.escape(fee.id) + '">' +
            "<td>" + (student ? u.avatarPair(student.name, student.admissionNo) : "—") + "</td>" +
            '<td><span class="cell-strong">' + u.escape(cls ? cls.name : "—") + '</span><span class="cell-sub">' + u.escape(program ? program.code : "") + " · Sem " + (student ? student.semester : "—") + "</span></td>" +
            '<td><span class="cell-strong">' + u.escape(fee.type) + '</span><span class="cell-sub">' + u.escape(fee.term) + "</span></td>" +
            '<td class="cell-num"><span class="fee-amount">' + u.formatMoney(fee.amount) + "</span></td>" +
            '<td><span class="fee-amount">' + u.formatMoney(fee.paid) + "</span>" +
              '<div class="progress fee-progress ' + progressTone + '" role="img" aria-label="' + paidPercent.toFixed(0) + '% of fees paid"><span style="width:' + paidPercent.toFixed(1) + '%"></span></div></td>' +
            '<td class="cell-num"><span class="fee-balance ' + (balance === 0 ? "paid" : "") + '">' + (balance === 0 ? "Settled" : u.formatMoney(balance)) + "</span></td>" +
            '<td><span class="cell-strong">' + u.formatDate(fee.dueDate, "short") + '</span><span class="cell-sub">' + u.formatDate(fee.dueDate, "weekday") + ", " + new Date(fee.dueDate + "T12:00:00").getFullYear() + "</span></td>" +
            "<td>" + ui.statusBadge(status) + "</td>" +
            '<td class="cell-actions"><div class="row-actions">' +
              '<button class="icon-action" type="button" data-view-fee="' + u.escape(fee.id) + '" aria-label="View fee record for ' + u.escape(student ? student.name : "student") + '" title="View fee record">' + ui.icon("eye") + "</button>" +
              '<button class="icon-action" type="button" data-pay-fee="' + u.escape(fee.id) + '" aria-label="Record a payment for ' + u.escape(student ? student.name : "student") + '" title="Record payment"' + (balance === 0 ? " disabled" : "") + ">" + ui.icon("credit-card") + "</button>" +
              (fee.payments && fee.payments.length ? '<button class="icon-action" type="button" data-receipt-fee="' + u.escape(fee.id) + '" aria-label="Preview receipt for ' + u.escape(student ? student.name : "student") + '" title="Preview latest receipt">' + ui.icon("receipt") + "</button>" : "") +
            "</div></td></tr>";
        }).join("") +
        "</tbody></table></div>" +
        ui.pager({ page: state.page, pages: pages, total: list.length, pageSize: state.pageSize, label: "fee records" });
    }

    function paint() {
      const list = filtered();
      const region = root.querySelector("#feesTableRegion");
      if (region) region.innerHTML = tableHTML(list);
      const stats = root.querySelector("#feeStats");
      if (stats) stats.innerHTML = statsHTML();
      const count = root.querySelector("#feeCount");
      if (count) count.textContent = list.length === CMS.data.fees.length ? u.formatNumber(CMS.data.fees.length) : list.length + " of " + CMS.data.fees.length;
    }

    function fieldError(form, name, message) {
      const input = form.elements[name];
      const node = form.querySelector('[data-error-for="' + name + '"]');
      if (node) node.textContent = message || "";
      if (input) {
        if (message) input.setAttribute("aria-invalid", "true");
        else input.removeAttribute("aria-invalid");
      }
    }

    function openPayment(fee, drawerClose) {
      const student = CMS.student(fee.studentId);
      const balance = Math.max(0, Number(fee.amount) - Number(fee.paid));
      if (balance <= 0) {
        ui.toast("This fee account is already settled in full.", "info", "Nothing to collect");
        return;
      }
      const body = '<form id="paymentForm" novalidate>' +
        '<div class="fee-summary-top"><div><span class="badge ' + (CMS.feeStatus(fee) === "Overdue" ? "badge-overdue" : "badge-pending") + ' no-dot">' + u.escape(CMS.feeStatus(fee)) + "</span>" +
          '<div class="amount">' + u.formatMoney(balance) + ' <span>balance due</span></div></div><span class="pill">' + u.escape(fee.term) + "</span></div>" +
        '<div class="form-grid">' +
          '<div class="field span-2"><label for="payFeeType">Fee account</label><input id="payFeeType" type="text" value="' + u.escape((student ? student.name + " · " : "") + fee.type) + '" readonly /></div>' +
          '<div class="field"><label for="payAmount">Payment amount <span class="text-danger">*</span></label>' +
            '<input id="payAmount" name="amount" type="number" min="1" max="' + balance + '" step="0.01" value="' + balance.toFixed(2) + '" autofocus aria-describedby="payAmountError" />' +
            '<p class="field-error" id="payAmountError" data-error-for="amount" role="alert"></p></div>' +
          '<div class="field"><label for="payDate">Payment date <span class="text-danger">*</span></label>' +
            '<input id="payDate" name="date" type="date" max="' + u.todayISO() + '" value="' + u.todayISO() + '" aria-describedby="payDateError" />' +
            '<p class="field-error" id="payDateError" data-error-for="date" role="alert"></p></div>' +
          '<div class="field"><label for="payMethod">Payment method <span class="text-danger">*</span></label>' +
            '<select id="payMethod" name="method"><option>Bank transfer</option><option>Card</option><option>Cash</option><option>Cheque</option></select></div>' +
          '<div class="field"><label for="payReference">Reference / note</label><input id="payReference" name="reference" type="text" placeholder="e.g. deposit slip 4482" /></div>' +
          '<div class="field span-2"><div class="form-note">' + ui.icon("info", 14) + "<span>This prototype does not connect to a payment provider. Recording a payment only updates the demo record stored in this browser.</span></div></div>" +
        "</div></form>";

      ui.modal.open({
        title: "Record a fee payment",
        subtitle: (student ? student.name : "Student") + " · " + fee.term,
        body: body,
        footer: '<button class="btn btn-outline" type="button" data-modal-close>Cancel</button>' +
          '<button class="btn btn-primary" type="submit" form="paymentForm">' + ui.icon("check", 15) + " Record payment</button>",
        onMount: function (modal, close) {
          const form = modal.querySelector("#paymentForm");
          form.addEventListener("input", function (event) {
            if (event.target.name) fieldError(form, event.target.name, "");
          });
          form.addEventListener("submit", function (event) {
            event.preventDefault();
            form.querySelectorAll(".field-error").forEach(function (node) { node.textContent = ""; });
            form.querySelectorAll("[aria-invalid='true']").forEach(function (node) { node.removeAttribute("aria-invalid"); });
            const amount = Number(form.elements.amount.value);
            const date = form.elements.date.value;
            const method = form.elements.method.value;
            let valid = true;
            if (!form.elements.amount.value || isNaN(amount) || amount <= 0) {
              fieldError(form, "amount", "Enter a payment amount greater than zero.");
              valid = false;
            } else if (amount > balance + 0.001) {
              fieldError(form, "amount", "The amount cannot be greater than the outstanding balance of " + u.formatMoney(balance) + ".");
              valid = false;
            }
            if (!date) {
              fieldError(form, "date", "Choose the date the payment was received.");
              valid = false;
            } else if (date > u.todayISO()) {
              fieldError(form, "date", "The payment date cannot be in the future.");
              valid = false;
            }
            if (!valid) {
              const first = form.querySelector("[aria-invalid='true']");
              if (first) first.focus();
              return;
            }

            const receiptNo = "RCPT-" + new Date().getFullYear() + "-" + String(7100 + CMS.data.fees.reduce(function (count, item) { return count + (item.payments ? item.payments.length : 0); }, 0));
            const payment = {
              id: u.uid("pay"),
              date: date,
              amount: Math.round(amount * 100) / 100,
              method: method,
              receiptNo: receiptNo
            };
            fee.payments = fee.payments || [];
            fee.payments.push(payment);
            fee.paid = Math.min(Number(fee.amount), Math.round((Number(fee.paid) + payment.amount) * 100) / 100);
            CMS.store.save();
            close();
            if (drawerClose) drawerClose();
            paint();
            ui.toast(u.formatMoney(payment.amount) + " recorded for " + (student ? student.name : "this student") + ". Receipt " + receiptNo + ".", "success", "Payment recorded");
          });
        }
      });
    }

    function openDrawer(fee) {
      const student = CMS.student(fee.studentId);
      const cls = student ? CMS.classInfo(student.classId) : null;
      const program = student ? CMS.program(student.programId) : null;
      const balance = Math.max(0, Number(fee.amount) - Number(fee.paid));
      const status = CMS.feeStatus(fee);
      const payments = fee.payments || [];

      const body = '<div class="fee-summary-top"><div><span class="badge ' + u.statusClass(status) + '">' + u.escape(status) + "</span>" +
        '<div class="amount">' + (balance ? u.formatMoney(balance) : "Settled") + " <span>" + (balance ? "balance due" : "in full") + "</span></div></div>" +
        '<span class="pill">' + u.escape(fee.term) + "</span></div>" +
        '<div class="detail-profile">' + u.avatar(student ? student.name : "Student", "lg") +
          "<div><h3>" + u.escape(student ? student.name : "Student") + "</h3><p>" + u.escape(student ? student.admissionNo : "") + " · " + u.escape(cls ? cls.name : "") + "</p>" +
          (student ? u.statusBadge(student.status) : "") + "</div></div>" +
        '<div class="detail-section"><h4 class="detail-section-title">' + ui.icon("file-text", 13) + " Fee details</h4>" +
          '<div class="info-list">' +
            '<div class="info-row"><span>Fee type</span><strong>' + u.escape(fee.type) + "</strong></div>" +
            '<div class="info-row"><span>Programme</span><strong>' + u.escape(program ? program.name : "—") + "</strong></div>" +
            '<div class="info-row"><span>Total billed</span><strong>' + u.formatMoney(fee.amount) + "</strong></div>" +
            '<div class="info-row"><span>Paid to date</span><strong>' + u.formatMoney(fee.paid) + "</strong></div>" +
            '<div class="info-row"><span>Balance</span><strong>' + (balance ? u.formatMoney(balance) : "Settled") + "</strong></div>" +
            '<div class="info-row"><span>Due date</span><strong>' + u.formatDate(fee.dueDate, "medium") + "</strong></div>" +
          "</div></div>" +
        '<div class="detail-section"><h4 class="detail-section-title">' + ui.icon("receipt", 13) + " Payment history</h4>" +
          (payments.length ? '<div class="payment-history">' + payments.slice().reverse().map(function (payment) {
            return '<div class="payment-item"><span class="payment-item-icon">' + ui.icon("check", 14) + "</span>" +
              '<div class="payment-copy"><strong>' + u.formatMoney(payment.amount) + " · " + u.escape(payment.method) + "</strong><span>" + u.formatDate(payment.date, "medium") + " · " + u.escape(payment.receiptNo) + "</span></div>" +
              '<button class="link-btn" type="button" data-print-receipt="' + u.escape(fee.id) + '" data-payment="' + u.escape(payment.id) + '">Receipt</button></div>';
          }).join("") + "</div>" : ui.emptyState({ icon: "receipt", title: "No payments recorded", text: "Payments will appear here once they are received.", compact: true })) +
        "</div>";

      const footer = '<button class="btn btn-danger-soft" type="button" data-statement="' + u.escape(fee.id) + '">' + ui.icon("printer", 15) + " Print statement</button>" +
        '<button class="btn btn-outline" type="button" data-drawer-close>Close</button>' +
        '<button class="btn btn-primary" type="button" data-pay-fee="' + u.escape(fee.id) + '"' + (balance === 0 ? " disabled" : "") + ">" + ui.icon(balance === 0 ? "check-circle" : "credit-card", 15) + (balance === 0 ? " Paid in full" : " Record payment") + "</button>";

      const ref = ui.drawer.open({
        title: "Fee account",
        subtitle: fee.type,
        body: body,
        footer: footer,
        onMount: function (drawer) {
          drawer.addEventListener("click", function (event) {
            const receiptButton = event.target.closest("[data-print-receipt]");
            if (receiptButton) {
              const targetFee = CMS.byId("fees", receiptButton.getAttribute("data-print-receipt"));
              const payment = targetFee && targetFee.payments ? targetFee.payments.find(function (p) { return p.id === receiptButton.getAttribute("data-payment"); }) : null;
              if (targetFee && payment) showDocument("Receipt " + payment.receiptNo, statementHTML(targetFee, payment), "Fee receipt · " + payment.receiptNo);
              return;
            }
            const statement = event.target.closest("[data-statement]");
            if (statement) {
              const targetFee = CMS.byId("fees", statement.getAttribute("data-statement"));
              if (targetFee) showDocument("Fee statement", statementHTML(targetFee), "Fee statement · " + targetFee.term);
              return;
            }
            const pay = event.target.closest("[data-pay-fee]");
            if (pay) {
              const targetFee = CMS.byId("fees", pay.getAttribute("data-pay-fee"));
              if (targetFee) openPayment(targetFee, ref.close);
            }
          });
        }
      });
    }

    const classOptions = CMS.data.classes.map(function (cls) {
      return '<option value="' + cls.id + '"' + (state.classId === cls.id ? " selected" : "") + ">" + u.escape(cls.name) + "</option>";
    }).join("");

    root.innerHTML =
      '<div class="view-head"><div class="view-head-copy"><p class="eyebrow">Administration · Student accounts</p><h1 class="view-title">Fees</h1>' +
        '<p class="view-sub">Review fee accounts, record demo payments, and print receipts or statements. No real payment is processed.</p></div>' +
        '<div class="view-actions"><a class="btn btn-outline" href="app.html#/reports?type=fees">' + ui.icon("chart", 15) + ' Fee report</a>' +
        '<button class="btn btn-primary" type="button" id="exportFees">' + ui.icon("download", 15) + " Export CSV</button></div></div>" +
      '<div id="feeStats"></div>' +
      '<div class="card table-card">' +
        '<div class="table-toolbar">' +
          '<div class="toolbar-search">' + ui.icon("search") + '<input type="search" id="feeSearch" value="' + u.escape(state.q) + '" placeholder="Search student, admission no., or fee type" aria-label="Search fee records" /></div>' +
          '<select class="select-compact" id="feeStatus" aria-label="Filter by payment status">' +
            '<option value="all"' + (state.status === "all" ? " selected" : "") + ">All statuses</option>" +
            ["paid", "pending", "overdue"].map(function (status) {
              return '<option value="' + status + '"' + (state.status === status ? " selected" : "") + ">" + status.charAt(0).toUpperCase() + status.slice(1) + "</option>";
            }).join("") +
          "</select>" +
          '<select class="select-compact" id="feeClass" aria-label="Filter by class"><option value="all">All classes</option>' + classOptions + "</select>" +
          '<div class="toolbar-divider" aria-hidden="true"></div>' +
          '<span class="toolbar-count"><strong id="feeCount">' + CMS.data.fees.length + "</strong> accounts</span>" +
        "</div>" +
        '<div id="feesTableRegion"></div>' +
      "</div>";

    const search = root.querySelector("#feeSearch");
    const status = root.querySelector("#feeStatus");
    const classSelect = root.querySelector("#feeClass");

    search.addEventListener("input", u.debounce(function () {
      state.q = search.value;
      state.page = 1;
      paint();
    }, 140));
    status.addEventListener("change", function () {
      state.status = status.value;
      state.page = 1;
      paint();
    });
    classSelect.addEventListener("change", function () {
      state.classId = classSelect.value;
      state.page = 1;
      paint();
    });

    root.addEventListener("click", function (event) {
      if (event.target.closest("#feeStats")) return;
      const row = event.target.closest("[data-fee-row]");
      const sort = event.target.closest("[data-sort]");
      if (sort) {
        const key = sort.getAttribute("data-sort");
        if (state.sortKey === key) state.sortDir = state.sortDir === "asc" ? "desc" : "asc";
        else {
          state.sortKey = key;
          state.sortDir = key === "name" || key === "due" ? "asc" : "desc";
        }
        paint();
        return;
      }
      const pageBtn = event.target.closest("[data-page]");
      if (pageBtn && !pageBtn.disabled) {
        state.page = Number(pageBtn.getAttribute("data-page"));
        paint();
        const table = root.querySelector("#feesTableRegion");
        if (table) table.scrollIntoView({ behavior: "smooth", block: "start" });
        return;
      }
      if (event.target.closest("[data-clear-filters]")) {
        state.q = "";
        state.status = "all";
        state.classId = "all";
        state.page = 1;
        search.value = "";
        status.value = "all";
        classSelect.value = "all";
        paint();
        return;
      }
      const view = event.target.closest("[data-view-fee]");
      if (view) {
        const fee = CMS.byId("fees", view.getAttribute("data-view-fee"));
        if (fee) openDrawer(fee);
        return;
      }
      const pay = event.target.closest("[data-pay-fee]");
      if (pay && !pay.disabled) {
        const fee = CMS.byId("fees", pay.getAttribute("data-pay-fee"));
        if (fee) openPayment(fee);
        return;
      }
      const receipt = event.target.closest("[data-receipt-fee]");
      if (receipt) {
        const fee = CMS.byId("fees", receipt.getAttribute("data-receipt-fee"));
        if (fee && fee.payments && fee.payments.length) {
          const payment = fee.payments[fee.payments.length - 1];
          showDocument("Receipt " + payment.receiptNo, statementHTML(fee, payment), "Fee receipt · " + payment.receiptNo);
        }
      }
      if (row && !event.target.closest("button, a")) {
        const fee = CMS.byId("fees", row.getAttribute("data-fee-row"));
        if (fee) openDrawer(fee);
      }
    });

    root.querySelector("#exportFees").addEventListener("click", function () {
      const list = filtered();
      const rows = [["Student", "Admission no.", "Class", "Programme", "Fee type", "Term", "Billed (USD)", "Paid (USD)", "Balance (USD)", "Due date", "Status", "Receipts"]];
      list.forEach(function (fee) {
        const student = CMS.student(fee.studentId);
        const cls = student ? CMS.classInfo(student.classId) : null;
        const program = student ? CMS.program(student.programId) : null;
        rows.push([
          student ? student.name : "",
          student ? student.admissionNo : "",
          cls ? cls.name : "",
          program ? program.name : "",
          fee.type,
          fee.term,
          fee.amount,
          fee.paid,
          Math.max(0, Number(fee.amount) - Number(fee.paid)),
          fee.dueDate,
          CMS.feeStatus(fee),
          (fee.payments || []).map(function (p) { return p.receiptNo; }).join("; ")
        ]);
      });
      if (!list.length) {
        ui.toast("There are no fee records to export with the current filters.", "warning");
        return;
      }
      ui.downloadCSV("fees-" + u.todayISO() + ".csv", rows);
      ui.toast(list.length + " fee records exported as a CSV file.", "success", "Export ready");
    });

    paint();
  }

  CMS.views = CMS.views || {};
  CMS.views.fees = { render: render };
})();
